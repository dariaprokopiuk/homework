// Дан массив с числами. Увеличьте каждое число из массива на 10 процентов.
let arr = [100, 200, 50, 300]
let result = arr
    .map(num => num * 1.1) //каждый элемент массива увеличиваем на 10%
    .map(num => Number(num.toFixed(1))); // каждый элемент массива округялем до одного знака после точки
console.log(result)