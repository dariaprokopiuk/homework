// Дан массив с дробями: `[1.456, 2.125, 3.32, 4.1, 5.34]` Округлите эти дроби до одного знака в дробной части.
let arr = [1.456, 2.125, 3.32, 4.1, 5.34]
let result = arr.map(num => Number(num.toFixed(1)))
console.log(result)


//map - перебирает каждый элемент массив
//toFixed(1) - округляет до одного знака после запятой
// number - превращает строку в число 

